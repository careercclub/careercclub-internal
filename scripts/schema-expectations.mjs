// Emits SQL that asserts the database actually has every table and column the
// application's record catalog declares.
//
// Why this exists: tables restored from the Supabase dump were never created by a
// migration, and migration 001 uses `create table if not exists` — so for every table
// the dump already had, 001's column declarations silently never ran. The schema looks
// migrated, the migration ledger is green, and the app then fails at runtime with
// 42703 "column ... does not exist" the first time someone touches that field. That
// bug shipped three times (kol_list, master_produk, buyers.talent_pool) before this.
//
// The catalog is the app's own contract, so it is the right source of truth. Piped
// into psql by scripts/vps-rebuild-full.sh after migrations and before the build.
//
// Usage: node scripts/schema-expectations.mjs | psql ...

import { recordDefinitions } from "../lib/records/catalog.ts";

const expectations = new Map();
// Fields the catalog declares as list-valued must be real Postgres arrays. A jsonb
// column here still *exists*, so an existence-only check passes while every write
// fails at runtime with 42804 — which is exactly how tasks.assignee_ids shipped broken.
const arrayColumns = [];
for (const definition of Object.values(recordDefinitions)) {
  const columns = expectations.get(definition.table) || new Set();
  for (const field of definition.fields) {
    columns.add(field.name);
    if (field.type === "uuid-array" || field.type === "text-array") arrayColumns.push(`('${definition.table}','${field.name}')`);
  }
  expectations.set(definition.table, columns);
}

const rows = [...expectations.entries()].flatMap(([table, columns]) =>
  [...columns].map((column) => `('${table}','${column}')`),
);

process.stdout.write(`-- generated by scripts/schema-expectations.mjs — do not edit
do $$
declare
  missing_tables text;
  missing_columns text;
  -- Each check reports independently. An early return here would let one class of
  -- problem mask another, so a database with a missing column would never reach the
  -- array-type check and the second migration would only surface after the first.
  problems boolean := false;
begin
  create temporary table ccc_expected_columns (table_name text, column_name text) on commit drop;
  insert into ccc_expected_columns (table_name, column_name) values
    ${rows.join(",\n    ")};

  select string_agg(distinct e.table_name, ', ' order by e.table_name)
  into missing_tables
  from ccc_expected_columns e
  where to_regclass('public.' || quote_ident(e.table_name)) is null;

  -- Reported, not raised. A missing column breaks one feature; aborting the deploy
  -- breaks everything, so this surfaces the gap without holding the release hostage.
  -- The grant check above still aborts, because a bad grant breaks whole pages.
  if missing_tables is not null then
    raise warning 'Tables the application expects are MISSING: %', missing_tables;
    raise warning 'Add a migration creating them — 001 uses "create table if not exists" and was skipped for dump-restored tables.';
    problems := true;
  end if;

  select string_agg(format('%s.%s', e.table_name, e.column_name), ', ' order by e.table_name, e.column_name)
  into missing_columns
  from ccc_expected_columns e
  where not exists (
    select 1 from information_schema.columns c
    where c.table_schema = 'public'
      and c.table_name = e.table_name
      and c.column_name = e.column_name
  );

  if missing_columns is not null then
    raise warning 'Columns the application expects are MISSING: %', missing_columns;
    raise warning 'Add a migration with "alter table ... add column if not exists" for each (see 022_restore_dump_only_columns.sql).';
    problems := true;
  end if;

  -- Type check for list-valued columns. Reported separately because a wrong type is a
  -- different failure from a missing column and needs a different migration.
  create temporary table ccc_expected_arrays (table_name text, column_name text) on commit drop;
  insert into ccc_expected_arrays (table_name, column_name) values
    ${arrayColumns.join(",\n    ")};

  select string_agg(format('%s.%s (is %s, expected ARRAY)', a.table_name, a.column_name, c.data_type), ', ' order by a.table_name, a.column_name)
  into missing_columns
  from ccc_expected_arrays a
  join information_schema.columns c
    on c.table_schema = 'public' and c.table_name = a.table_name and c.column_name = a.column_name
  where c.data_type <> 'ARRAY';

  if missing_columns is not null then
    raise warning 'Columns that must be Postgres arrays have the WRONG TYPE: %', missing_columns;
    raise warning 'Writes to these fail with 42804 — convert them (see 024_tasks_assignee_ids_uuid_array.sql).';
    problems := true;
  end if;

  if problems then return; end if;

  raise notice 'Schema check passed: % tables, % columns, % array columns.',
    (select count(distinct table_name) from ccc_expected_columns),
    (select count(*) from ccc_expected_columns),
    (select count(*) from ccc_expected_arrays);
end
$$;
`);
