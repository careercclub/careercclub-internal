// Emits SQL that asserts the database actually has every table and column the
// application's record catalog declares.
//
// Why this exists: tables restored from the Supabase dump were never created by a
// migration, and migration 001 uses `create table if not exists` — so for every table
// the dump already had, 001's column declarations silently never ran. The schema looks
// migrated, the migration ledger is green, and the app then fails at runtime with
// 42703 "column ... does not exist" the first time someone touches that field. That
// bug shipped three times (kol_list, master_produk, buyers.talent_pool) before this.
//
// The catalog is the app's own contract, so it is the right source of truth. Piped
// into psql by scripts/vps-rebuild-full.sh after migrations and before the build.
//
// Usage: node scripts/schema-expectations.mjs | psql ...

import { recordDefinitions } from "../lib/records/catalog.ts";

const expectations = new Map();
for (const definition of Object.values(recordDefinitions)) {
  const columns = expectations.get(definition.table) ?? new Set();
  for (const field of definition.fields) columns.add(field.name);
  expectations.set(definition.table, columns);
}

const rows = [...expectations.entries()].flatMap(([table, columns]) =>
  [...columns].map((column) => `('${table}','${column}')`),
);

process.stdout.write(`-- generated by scripts/schema-expectations.mjs — do not edit
do $$
declare
  missing_tables text;
  missing_columns text;
begin
  create temporary table ccc_expected_columns (table_name text, column_name text) on commit drop;
  insert into ccc_expected_columns (table_name, column_name) values
    ${rows.join(",\n    ")};

  select string_agg(distinct e.table_name, ', ' order by e.table_name)
  into missing_tables
  from ccc_expected_columns e
  where to_regclass('public.' || quote_ident(e.table_name)) is null;

  if missing_tables is not null then
    raise exception using
      message = format('Tables the application expects are missing: %s', missing_tables),
      hint = 'Add a migration creating them. Note that 001 uses "create table if not exists" and was skipped for dump-restored tables.';
  end if;

  select string_agg(format('%s.%s', e.table_name, e.column_name), ', ' order by e.table_name, e.column_name)
  into missing_columns
  from ccc_expected_columns e
  where not exists (
    select 1 from information_schema.columns c
    where c.table_schema = 'public'
      and c.table_name = e.table_name
      and c.column_name = e.column_name
  );

  if missing_columns is not null then
    raise exception using
      message = format('Columns the application expects are missing: %s', missing_columns),
      hint = 'Add a migration with "alter table ... add column if not exists" for each (see 022_restore_dump_only_columns.sql).';
  end if;

  raise notice 'Schema check passed: % tables, % columns.',
    (select count(distinct table_name) from ccc_expected_columns),
    (select count(*) from ccc_expected_columns);
end
$$;
`);
